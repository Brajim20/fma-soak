"""Facts for the "is this intended?" check on a new digest finding (task 4.6).

Not a verdict: a person still decides. For each new finding it gathers what that check starts from: the app's
manifest and input (and the install/uninstall scripts the host ran), the last commits to the app's input, fleetdm/fleet
issues that mention the app, and the Fleet code behind the failing step, linked at the build the finding ran on.

Cached per app and day in results/context/<date>/, so a digest rebuilt every pass asks GitHub once. GitHub calls go
through `gh` (GH_TOKEN in CI); without it the context says so and the digest still builds.

  python3 context.py <slug> <shape> <build>      # print one finding's context
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import runner as R

GH = "https://github.com/fleetdm/fleet/blob"
# the Fleet code behind each kind of failure (paths checked at 937e87458c, 4.94.0 RC)
CODE = {
    "add": ["ee/server/service/maintained_apps.go"],
    "install": ["orbit/pkg/installer/installer.go"],
    "uninstall": ["orbit/pkg/installer/installer.go"],
    "S1": ["server/datastore/mysql/software_installers.go", "server/datastore/mysql/software.go"],
    "S2": ["orbit/pkg/installer/installer.go"],
    "S3": ["orbit/pkg/installer/installer.go"],
    "S4": ["ee/server/service/maintained_apps_auto_update.go", "server/datastore/mysql/software_installers.go"],
    "S5": [],
}
INGESTER = {"darwin": ("homebrew", "ee/maintained-apps/ingesters/homebrew/scripts.go"),
            "windows": ("winget", "ee/maintained-apps/ingesters/winget/ingester.go")}


def gh(*args):
    r = subprocess.run(["gh", *args], capture_output=True, text=True, timeout=60)
    if r.returncode:
        raise RuntimeError((r.stderr or r.stdout).strip()[:160])
    return json.loads(r.stdout or "null")


def on_main(path):
    return subprocess.run(["git", "-C", R.REPO, "cat-file", "-e", f"origin/main:{path}"], capture_output=True).returncode == 0


def gather(slug, shape, build, date):
    base, plat = slug.split("/")
    cache = os.path.join(R.WS, "results", "context", date, f"{base}_{plat}.json")
    if os.path.exists(cache):
        return json.load(open(cache))
    src, ingester = INGESTER[plat]
    rev = (re.search(r"\(([0-9a-f]{7,40})\)", build or "") or [None, "main"])[1]
    files = [f"ee/maintained-apps/outputs/{base}/{plat}.json", f"ee/maintained-apps/inputs/{src}/{base}.json"]
    if plat == "windows":
        files += [p for p in (f"ee/maintained-apps/inputs/winget/scripts/{base}_install.ps1",
                              f"ee/maintained-apps/inputs/winget/scripts/{base}_uninstall.ps1") if on_main(p)]
    else:
        files.append(ingester)  # macOS scripts are generated by the ingester, not stored per app
    ctx = {"files": [f"{GH}/main/{p}" for p in files if p == ingester or on_main(p)],
           "code": [f"{GH}/{rev}/{p}" for p in CODE.get(shape, [])]}
    try:
        name = R.catalog_manifest(slug).get("name") or base
    except Exception:
        name = base
    try:
        seen, commits = set(), []
        for p in files[1:]:
            if p == ingester:
                continue
            for c in gh("api", f"repos/fleetdm/fleet/commits?path={p}&per_page=3") or []:
                if c["sha"] in seen:
                    continue
                seen.add(c["sha"])
                commits.append({"sha": c["sha"][:10], "date": c["commit"]["committer"]["date"][:10],
                                "title": c["commit"]["message"].splitlines()[0][:90]})
        ctx["commits"] = sorted(commits, key=lambda c: c["date"], reverse=True)[:3]
        q = f'repo:fleetdm/fleet is:issue "{name}" in:title,body'  # PRs are mostly nightly catalog bumps; commits cover them
        hits = gh("api", "-X", "GET", "search/issues", "-f", f"q={q}", "-f", "per_page=5")
        ctx["issues"] = [{"number": i["number"], "state": i["state"], "title": i["title"][:90]}
                         for i in (hits or {}).get("items", [])]
    except Exception as e:
        ctx["github_error"] = f"{type(e).__name__}: {e}"
    os.makedirs(os.path.dirname(cache), exist_ok=True)
    json.dump(ctx, open(cache, "w"), indent=1)
    return ctx


def line(ctx):
    """One markdown line for the digest and the alert issue."""
    parts = ["files: " + ", ".join(f"[{u.rsplit('/', 1)[1]}]({u})" for u in ctx.get("files", []))]
    if ctx.get("code"):
        parts.append("code at this build: " + ", ".join(f"[{u.rsplit('/', 1)[1]}]({u})" for u in ctx["code"]))
    if ctx.get("commits"):
        parts.append("last changes: " + "; ".join(f"{c['date']} {c['title']}" for c in ctx["commits"]))
    if "issues" in ctx:
        parts.append("issues mentioning it: " + (", ".join(f"#{i['number']} ({i['state']})" for i in ctx["issues"]) or "none"))
    if ctx.get("github_error"):
        parts.append(f"(GitHub lookups failed: {ctx['github_error']})")
    return " · ".join(parts)


if __name__ == "__main__":
    slug, shape, build = sys.argv[1:4]
    import datetime
    c = gather(slug, shape, build, datetime.date.today().isoformat())
    print(json.dumps(c, indent=1))
    print(line(c))
